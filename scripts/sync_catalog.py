#!/usr/bin/env python3
"""Synchronize generated skill metadata and the human catalog."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parent.parent
CATALOG_PATH = ROOT / "skills" / "catalog.yaml"
DOC_PATH = ROOT / "docs" / "SKILL_CATALOG.md"
ASSISTANT_ROUTES_PATH = ROOT / "skills/primitives/research-assistant/assets/workflow-routes.json"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    return parser.parse_args()


def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def openai_yaml(skill: dict[str, str]) -> str:
    lines = [
        "interface:",
        f"  display_name: {quoted(skill['display_name'])}",
        f"  short_description: {quoted(skill['short_description'])}",
        f"  default_prompt: {quoted(skill['default_prompt'])}",
    ]
    if skill["invocation"] == "user":
        lines.extend(
            [
                "policy:",
                "  allow_implicit_invocation: false",
            ]
        )
    return "\n".join(lines) + "\n"


def catalog_doc(catalog: dict[str, object]) -> str:
    skills = catalog["skills"]
    lines = [
        "# Skill catalog",
        "",
        "<!-- Generated by scripts/sync_catalog.py; edit skills/catalog.yaml. -->",
        "",
        f"Research OS {catalog['version']} contains {len(skills)} catalogued skills.",
        "",
    ]
    for bucket in ("orchestrators", "primitives", "meta"):
        bucket_skills = [skill for skill in skills if skill["bucket"] == bucket]
        lines.extend(
            [
                f"## {bucket.title()}",
                "",
                "| Skill | Invocation | Leading concept | Purpose |",
                "|---|---|---|---|",
            ]
        )
        for skill in bucket_skills:
            path = f"../skills/{bucket}/{skill['name']}/SKILL.md"
            lines.append(
                f"| [`{skill['name']}`]({path}) | {skill['invocation']} | "
                f"{skill['leading_word']} | {skill['description']} |"
            )
        lines.append("")
    return "\n".join(lines)


def reconcile(path: Path, expected: str, check: bool, errors: list[str]) -> None:
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == expected:
        return
    if check:
        errors.append(f"out of sync: {path.relative_to(ROOT)}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(expected, encoding="utf-8")
    print(f"WROTE {path.relative_to(ROOT)}")


def main() -> int:
    args = parse_args()
    catalog = yaml.safe_load(CATALOG_PATH.read_text(encoding="utf-8"))
    errors: list[str] = []
    for skill in catalog["skills"]:
        path = (
            ROOT
            / "skills"
            / skill["bucket"]
            / skill["name"]
            / "agents"
            / "openai.yaml"
        )
        reconcile(path, openai_yaml(skill), args.check, errors)
    reconcile(DOC_PATH, catalog_doc(catalog), args.check, errors)
    skills_by_name = {s["name"]: s for s in catalog["skills"]}
    routes = {
        "schema_version": 1,
        "source": "skills/catalog.yaml:assistant_delegation",
        "native_policy_override": False,
        "workflows": [
            {key: skills_by_name[name][key] for key in ("name", "bucket", "invocation", "description")}
            for name in catalog.get("assistant_delegation", [])
        ],
    }
    reconcile(ASSISTANT_ROUTES_PATH, json.dumps(routes, ensure_ascii=False, indent=2) + "\n", args.check, errors)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    print(f"SYNC OK: {len(catalog['skills'])} skills")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
